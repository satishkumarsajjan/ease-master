import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.join(__dirname, "..")

const REGISTRY_FILE = path.join(ROOT, "registry/index.ts")
const META_FILE = path.join(ROOT, "registry/meta.ts")

function extractString(body, fieldName) {
  const escaped = fieldName.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
  const regex = new RegExp(`${escaped}\\s*:\\s*["']([^"']*)["']`, "m")
  const match = body.match(regex)
  return match ? match[1] : undefined
}

function parseRegistryEntries(text) {
  const entries = []
  const entryRegex = /"([^"]+)":\s*\{/g
  let match

  while ((match = entryRegex.exec(text)) !== null) {
    const slug = match[1]
    const startIndex = match.index + match[0].length - 1

    let depth = 0
    let i = startIndex
    while (i < text.length) {
      if (text[i] === "{") depth++
      else if (text[i] === "}") depth--
      if (depth === 0) {
        const body = text.slice(startIndex + 1, i)
        entries.push({ slug, body })
        break
      }
      i++
    }
  }

  return entries
}

function parseEntryBody(body) {
  const result = {}

  const name = extractString(body, "name")
  if (name) result.name = name

  const type = extractString(body, "type")
  if (type) result.type = type

  const renderMode = extractString(body, "renderMode")
  if (renderMode) result.renderMode = renderMode

  const previewUrl = extractString(body, "previewUrl")
  if (previewUrl) result.previewUrl = previewUrl

  const installCommand = extractString(body, "installCommand")
  if (installCommand) result.installCommand = installCommand

  const mediaUrl = extractString(body, "mediaUrl")
  if (mediaUrl) result.mediaUrl = mediaUrl

  return result
}

function generateMetaTs(entries) {
  const lines = [
    `// AUTO-GENERATED by scripts/build-registry-meta.mjs`,
    `// Do not edit manually. Run the script after modifying registry/index.ts`,
    ``,
    `export interface RegistryMetaItem {`,
    `  /** Display name of the component demo */`,
    `  name: string`,
    `  /** Asset type */`,
    `  type?: "react" | "video" | "image"`,
    `  /** Render mode */`,
    `  renderMode?: "direct" | "iframe"`,
    `  /** URL to the isolated preview page */`,
    `  previewUrl?: string`,
    `  /** CLI install command */`,
    `  installCommand?: string`,
    `  /** URL to media asset */`,
    `  mediaUrl?: string`,
    `}`,
    ``,
    `export const registryMeta: Record<string, RegistryMetaItem> = {`,
  ]

  for (const entry of entries) {
    const meta = parseEntryBody(entry.body)
    if (!meta.name) continue

    lines.push(`  "${entry.slug}": {`)

    if (meta.name) lines.push(`    name: "${meta.name}",`)
    if (meta.type) lines.push(`    type: "${meta.type}",`)
    if (meta.renderMode) lines.push(`    renderMode: "${meta.renderMode}",`)
    if (meta.previewUrl) lines.push(`    previewUrl: "${meta.previewUrl}",`)
    if (meta.installCommand) lines.push(`    installCommand: "${meta.installCommand}",`)
    if (meta.mediaUrl) lines.push(`    mediaUrl: "${meta.mediaUrl}",`)

    lines.push(`  },`)
    lines.push(``)
  }

  lines.push(`}`)
  lines.push(``)

  return lines.join("\n")
}

function main() {
  console.log(`Reading ${REGISTRY_FILE}...`)
  const text = fs.readFileSync(REGISTRY_FILE, "utf-8")

  console.log(`Parsing registry entries...`)
  const entries = parseRegistryEntries(text)
  console.log(`Found ${entries.length} entries`)

  const metaTs = generateMetaTs(entries)

  fs.writeFileSync(META_FILE, metaTs, "utf-8")
  console.log(`✅ Written ${META_FILE}`)
}

main()
